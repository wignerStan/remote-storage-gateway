// Package descriptor owns the normative versioned plugin descriptor values.
// Parsing, framework schema generation and runtime admission are separate facets.
package descriptor

import (
	"encoding/json"
	"regexp"
)

const Schema = "network-data-plane-worker/plugin-descriptor/v2"
const MaxBytes = 1 << 20

var digest = regexp.MustCompile(`^sha256:[a-f0-9]{64}$`)

func ValidDigest(value string) bool { return digest.MatchString(value) }

type Descriptor struct {
	Schema          string           `json:"schema"`
	PluginID        string           `json:"plugin_id"`
	PluginVersion   string           `json:"plugin_version"`
	Contract        string           `json:"contract"`
	Runtime         string           `json:"runtime"`
	BuildDigest     string           `json:"build_digest"`
	Implementations []Implementation `json:"implementations"`
}
type Implementation struct {
	ID           string       `json:"id"`
	DisplayName  string       `json:"display_name,omitempty"`
	ConfigSchema ConfigSchema `json:"config_schema" doc:"Standard JSON Schema generated by the concrete plugin from its public configuration type."`
	Capabilities []string     `json:"capabilities"`
}
type ConfigSchema = json.RawMessage
type Record struct {
	Descriptor Descriptor
	Bytes      []byte
	Digest     string
}

func (d Descriptor) Implementation(id string) (Implementation, bool) {
	for _, implementation := range d.Implementations {
		if implementation.ID == id {
			return implementation, true
		}
	}
	return Implementation{}, false
}
